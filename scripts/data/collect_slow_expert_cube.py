# ---------------------------------------------------------------------------
# Oracle subclass — fix OGBench's max_step reset bug (see collect_expert_scene.py)
# ---------------------------------------------------------------------------
class CubeMarkovOracle(_BaseCubeMarkovOracle):
    def reset(self, ob, info):
        max_step = self._max_step
        super().reset(ob, info)
        self._max_step = max_step


# ---------------------------------------------------------------------------
# Policy wrapper: init-override + fixed goal + slowdown
# ---------------------------------------------------------------------------
class FixedGoalCubePolicy:
    """Expert policy for cube pick-and-place with random init + fixed goal.

    Responsibilities per episode:
      1. After env.reset(), override cube init position (random in left-half
         rectangle) and goal mocap target (fixed point).
      2. Reset the oracle with the new state.
      3. Produce scaled actions each step.
    """

    def __init__(
        self,
        env,
        init_bounds,   # dict with x_low, x_high, y_low, y_high
        goal_xyz,      # 3-tuple
        slowdown_factor=1.0,
        action_noise=0.0,
        min_norm=0.4,
        debug_cube=False,
    ):
        self.env = env  # unwrapped OGBCube env
        self.c = float(slowdown_factor)
        self.action_noise = float(action_noise)
        self.min_norm = float(min_norm)
        self.debug_cube = bool(debug_cube)
        self.debug_log = []
        self._debug_step = 0

        self.init_bounds = init_bounds
        self.goal_xyz = np.asarray(goal_xyz, dtype=np.float64)
        assert self.goal_xyz.shape == (3,)

        # Scale oracle max_step up for slow experts so lift/move phases don't
        # time out at low c values. Original OGBench default is 200.
        c_inv = max(1.0, 1.0 / self.c)
        self.oracle = CubeMarkovOracle(
            env=env, min_norm=min_norm, max_step=int(200 * c_inv),
        )
        self.done = False
        self._xi = 0.0

    # ----- init state override -----
    def reset_episode(self, rng: np.random.Generator):
        """Override env state: random init cube in left half, fixed target.
        Must be called AFTER env.reset() (which runs initialize_episode()
        and randomizes the scene under data_collection mode)."""
        env = self.env

        # 1. Override cube position (single cube: object_joint_0).
        x = float(rng.uniform(self.init_bounds['x_low'], self.init_bounds['x_high']))
        y = float(rng.uniform(self.init_bounds['y_low'], self.init_bounds['y_high']))
        yaw = float(rng.uniform(0.0, 2 * np.pi))
        env._data.joint('object_joint_0').qpos[:3] = [x, y, 0.02]
        env._data.joint('object_joint_0').qpos[3:] = lie.SO3.from_z_radians(yaw).wxyz.tolist()

        # 2. Override mocap target (single cube: index 0).
        env._target_task = 'cube'
        env._target_block = 0
        env._data.mocap_pos[env._cube_target_mocap_ids[0]] = self.goal_xyz.copy()
        env._data.mocap_quat[env._cube_target_mocap_ids[0]] = lie.SO3.identity().wxyz.tolist()
        # Hide any extra target mocaps (cube-single has num_cubes=1, but be safe).
        for i in range(1, len(env._cube_target_mocap_ids)):
            env._data.mocap_pos[env._cube_target_mocap_ids[i]] = (0.0, 0.0, -0.3)
            env._data.mocap_quat[env._cube_target_mocap_ids[i]] = lie.SO3.identity().wxyz.tolist()

        # 3. Sync physics and any derived env state.
        mujoco.mj_forward(env._model, env._data)

        # 4. Reset oracle state with the corrected info dict.
        info = env.compute_ob_info()
        self.oracle.reset(None, info)

        self.done = False
        self.debug_log = []
        self._debug_step = 0
        # Per-episode noise level (matches ExpertPolicy convention used in
        # collect_expert_scene.py).
        self._xi = float(rng.uniform(0.0, self.action_noise)) if self.action_noise > 0 else 0.0

    # ----- action generation -----
    def get_action(self):
        if self.done:
            return np.zeros(5, dtype=np.float32)

        info = self.env.compute_ob_info()
        action = np.array(self.oracle.select_action(None, info), dtype=np.float64)

        # Slowdown: scale position (0-2) and rotation (3), leave gripper (4).
        action[:4] *= self.c

        if self._xi > 0.0:
            xi = self._xi
            action = action + np.random.normal(
                0.0, [xi, xi, xi, xi * 3.0, xi * 10.0]
            )
        action = np.clip(action, -1.0, 1.0)

        if self.debug_cube:
            block_pos = info['privileged/block_0_pos']
            target_pos = info['privileged/target_block_pos']
            effector = info['proprio/effector_pos']
            self.debug_log.append({
                'step': self._debug_step,
                'block_pos': block_pos.copy().tolist(),
                'target_pos': target_pos.copy().tolist(),
                'effector': effector.copy().tolist(),
                'dist_eff': float(np.linalg.norm(block_pos - effector)),
                'dist_goal': float(np.linalg.norm(block_pos - target_pos)),
                'action': action.astype(np.float32).tolist(),
            })
            self._debug_step += 1

        if self.oracle.done:
            self.done = True

        return action.astype(np.float32)


# ---------------------------------------------------------------------------
# Physical success check (cube at goal, with tolerance)
# ---------------------------------------------------------------------------
def check_physical_success(env, goal_xyz, xy_tol=0.04, z_tol=0.04):
    cube_pos = env._data.joint('object_joint_0').qpos[:3].copy()
    d_xy = float(np.linalg.norm(cube_pos[:2] - np.asarray(goal_xyz)[:2]))
    d_z = abs(float(cube_pos[2] - goal_xyz[2]))
    success = (d_xy <= xy_tol) and (d_z <= z_tol)
    return success, {'cube_pos': cube_pos.tolist(), 'd_xy': d_xy, 'd_z': d_z}


# ---------------------------------------------------------------------------
# Step record + H5 writer (copied/trimmed from collect_expert_scene.py)
# ---------------------------------------------------------------------------
def _get_step_record(env, action, reward=0.0, terminated=False, truncated=False):
    import time as _time
    info = env.compute_ob_info()
    t0 = _time.time()
    info['pixels'] = env.render()
    info['render_time'] = _time.time() - t0
    info['observation'] = env.compute_observation()
    target = getattr(env, '_cur_goal_ob', None)
    if target is None:
        target = np.zeros_like(info['observation'])
    info['target'] = target
    info['action'] = action.astype(np.float32)
    info['step_idx'] = np.int64(0)
    info['success'] = env._success
    info['reward'] = np.float64(reward)
    info['terminated'] = bool(terminated)
    info['truncated'] = bool(truncated)
    return info


class H5Writer:
    """Incrementally write episodes to HDF5 (avoids OOM on large datasets)."""

    def __init__(self, path):
        from collections import defaultdict  # noqa: F401  (used indirectly)
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.f = h5py.File(
            str(self.path), 'w', libver='latest',
            fs_strategy='page', fs_page_size=4 * 1024 * 1024,
        )
        self._initialized = False
        self._global_step = 0
        self._ep_count = 0

    def _init_datasets(self, sample_step):
        for key, val in sample_step.items():
            if key.startswith('_'):
                continue
            h5key = key.replace('/', '_')
            arr = np.array(val)
            shape = (0,) + arr.shape
            maxshape = (None,) + arr.shape
            dtype = arr.dtype
            if np.issubdtype(dtype, np.str_) or np.issubdtype(dtype, np.bytes_) or dtype == object:
                dtype = h5py.string_dtype()
            if arr.ndim >= 2:  # images
                chunks = (100,) + arr.shape
                compression = hdf5plugin.Blosc(
                    cname='lz4', clevel=5, shuffle=hdf5plugin.Blosc.SHUFFLE,
                )
            else:
                chunks = (1000,) + arr.shape
                compression = None
            self.f.create_dataset(
                h5key, shape=shape, maxshape=maxshape, dtype=dtype,
                chunks=chunks, compression=compression,
            )
        self.f.create_dataset('ep_idx', shape=(0,), maxshape=(None,), dtype=np.int32, chunks=(1000,))
        self.f.create_dataset('ep_len', shape=(0,), maxshape=(None,), dtype=np.int32)
        self.f.create_dataset('ep_offset', shape=(0,), maxshape=(None,), dtype=np.int64)
        self._initialized = True

    def write_episode(self, ep_data):
        from collections import defaultdict
        if not self._initialized:
            self._init_datasets(ep_data[0])
        ep_len = len(ep_data)
        ep_arrays = defaultdict(list)
        for step in ep_data:
            for key, val in step.items():
                if key.startswith('_'):
                    continue
                ep_arrays[key.replace('/', '_')].append(val)
        for h5key, vals in ep_arrays.items():
            ds = self.f[h5key]
            old_len = ds.shape[0]
            ds.resize(old_len + ep_len, axis=0)
            ds[old_len:old_len + ep_len] = np.array(vals)
        ds = self.f['ep_idx']
        old_len = ds.shape[0]
        ds.resize(old_len + ep_len, axis=0)
        ds[old_len:old_len + ep_len] = self._ep_count
        meta_idx = self.f['ep_len'].shape[0]
        self.f['ep_len'].resize(meta_idx + 1, axis=0)
        self.f['ep_offset'].resize(meta_idx + 1, axis=0)
        self.f['ep_len'][meta_idx] = ep_len
        self.f['ep_offset'][meta_idx] = self._global_step
        self._global_step += ep_len
        self._ep_count += 1
        self.f.flush()

    def close(self):
        self.f.close()


# ---------------------------------------------------------------------------
# Collection loop
# ---------------------------------------------------------------------------
def collect(cfg, c, name, num_episodes, cache_dir, env=None, action_noise=None):
    if action_noise is None:
        action_noise = cfg.get('action_noise', 0.0)

    owns_env = env is None
    if owns_env:
        env = gym.make(
            'swm/OGBCube-v0',
            mode='data_collection',
            render_mode='rgb_array',
            width=cfg.world.image_shape[0],
            height=cfg.world.image_shape[1],
            max_episode_steps=cfg.world.max_episode_steps,
            terminate_at_goal=False,
            visualize_info=False,
        )

    init_bounds = dict(cfg.init_bounds)
    goal_xyz = tuple(cfg.goal_xyz)
    logging.info(
        f"Init bounds: x=[{init_bounds['x_low']}, {init_bounds['x_high']}]  "
        f"y=[{init_bounds['y_low']}, {init_bounds['y_high']}]   goal={goal_xyz}"
    )

    policy = FixedGoalCubePolicy(
        env.unwrapped,
        init_bounds=init_bounds,
        goal_xyz=goal_xyz,
        slowdown_factor=c,
        action_noise=action_noise,
        debug_cube=cfg.get('debug_cube', False),
    )

    rng = np.random.default_rng(cfg.seed)
    max_steps = cfg.world.max_episode_steps

    h5_path = Path(cache_dir) / f'{name}.h5'
    writer = H5Writer(h5_path)

    ep_lens = []
    successes = []

    for ep in tqdm(range(num_episodes), desc=f'Collecting slowdown_factor={c}'):
        ep_seed = rng.integers(0, 1_000_000).item()
        env.reset(seed=ep_seed)
        np.random.seed(ep_seed)
        ep_rng = np.random.default_rng(ep_seed)
        policy.reset_episode(ep_rng)

        init_action = np.full(5, np.nan, dtype=np.float32)
        ep_data = [_get_step_record(env.unwrapped, init_action)]

        n_steps = 0
        truncated_at_max = False
        for step in range(max_steps):
            action = policy.get_action()
            obs, reward, terminated, truncated, info = env.step(action)
            n_steps = step + 1

            # Check physical success every step
            success_now, _ = check_physical_success(env.unwrapped, goal_xyz)
            ep_data.append(_get_step_record(
                env.unwrapped, action,
                reward=reward, terminated=success_now, truncated=truncated,
            ))
            if success_now or policy.done:
                break
            if truncated:
                truncated_at_max = True
                break

        # Align actions: shift left so (o_t, a_t) pairs match record_dataset convention.
        for i in range(len(ep_data) - 1):
            ep_data[i]['action'] = ep_data[i + 1]['action']
        ep_data[-1]['action'] = np.full(5, np.nan, dtype=np.float32)
        for i, d in enumerate(ep_data):
            d['step_idx'] = np.int64(i)

        success, details = check_physical_success(env.unwrapped, goal_xyz)
        ep_lens.append(len(ep_data))
        successes.append(success)

        writer.write_episode(ep_data)

        if cfg.get('debug_cube', False) and len(policy.debug_log) > 0:
            dbg_dir = Path(cache_dir) / f'{name}_debug'
            dbg_dir.mkdir(parents=True, exist_ok=True)
            tag = 'success' if success else 'fail'
            dbg_path = dbg_dir / f'ep{ep:04d}_seed{ep_seed}_{tag}.txt'
            with open(dbg_path, 'w') as f:
                f.write(f"# c={c} ep={ep} seed={ep_seed} success={success} "
                        f"d_xy={details['d_xy']:.4f} d_z={details['d_z']:.4f}\n")
                for r in policy.debug_log:
                    f.write(
                        f"{r['step']:4d}  "
                        f"d_eff={r['dist_eff']:.4f}  d_goal={r['dist_goal']:.4f}  "
                        f"block={r['block_pos']}  eff={r['effector']}  "
                        f"act={r['action']}\n"
                    )

    writer.f.create_dataset('ep_physical_success', data=np.array(successes, dtype=bool))
    writer.close()
    if owns_env:
        env.close()

    ep_lens = np.array(ep_lens)
    successes = np.array(successes)
    logging.info(f"Saved {len(ep_lens)} episodes to {h5_path}")
    logging.info(f"Success rate: {successes.mean():.1%}")
    if successes.any():
        logging.info(
            f"TTC (successful only): "
            f"{ep_lens[successes].mean():.1f} ± {ep_lens[successes].std():.1f}"
        )
    return ep_lens, successes


# ---------------------------------------------------------------------------
# Video recording — side-by-side D_WM (c=1.0, noise) vs D_e (c, clean)
# ---------------------------------------------------------------------------
def record_comparison_video(cfg, c, output_dir, env, seed=42, ep_num=None, tag=None):
    """Record side-by-side video: D_WM(c=1.0, noise=0.1) vs D_e(c, noise=0).

    Mirrors collect_expert_scene.record_comparison_video but uses
    FixedGoalCubePolicy for our constrained-init + fixed-goal task.

    Args:
        env: Pre-created env to reuse (avoids EGL crash from concurrent contexts).
        seed: Episode seed.
        ep_num: Optional episode index for filename disambiguation.
        tag: Optional label ('fail' or 'success') for the filename.
    """
    import cv2
    import imageio

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    max_steps = cfg.world.max_episode_steps
    init_bounds = dict(cfg.init_bounds)
    goal_xyz = tuple(cfg.goal_xyz)

    def run_episode(slowdown, ep_seed, noise=0.0):
        policy = FixedGoalCubePolicy(
            env.unwrapped,
            init_bounds=init_bounds,
            goal_xyz=goal_xyz,
            slowdown_factor=slowdown,
            action_noise=noise,
        )
        # Seed order MUST EXACTLY match collect() so the same ep_seed
        # reproduces the same init cube placement.
        env.reset(seed=ep_seed)
        np.random.seed(ep_seed)
        rng = np.random.default_rng(ep_seed)
        policy.reset_episode(rng)

        frames = [env.unwrapped.render().copy()]
        for _ in range(max_steps):
            action = policy.get_action()
            obs, reward, terminated, truncated, info = env.step(action)
            frames.append(env.unwrapped.render().copy())
            if policy.done or truncated:
                break
        return frames

    frames_wm = run_episode(1.0, seed, noise=0.1)
    frames_de = run_episode(c, seed, noise=0.0)

    # Pad shorter video
    max_len = max(len(frames_wm), len(frames_de))
    while len(frames_wm) < max_len:
        frames_wm.append(frames_wm[-1])
    while len(frames_de) < max_len:
        frames_de.append(frames_de[-1])

    combined_frames = []
    for i in range(max_len):
        fw = frames_wm[i].copy()
        fe = frames_de[i].copy()
        cv2.putText(fw, f"D_WM (c=1.0, n=0.1)", (5, 20),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1)
        cv2.putText(fw, f"step {i}", (5, 40),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.4, (200, 200, 200), 1)
        cv2.putText(fe, f"D_e (c={c})", (5, 20),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255, 255, 255), 1)
        cv2.putText(fe, f"step {i}", (5, 40),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.4, (200, 200, 200), 1)
        sep = np.ones((fw.shape[0], 4, 3), dtype=np.uint8) * 255
        combined_frames.append(np.hstack([fw, sep, fe]))

    if ep_num is not None:
        tag_str = f'_{tag}' if tag else ''
        video_path = output_dir / f'diffusion_cube_c{c}{tag_str}_ep{ep_num:03d}_seed{seed}.mp4'
    else:
        video_path = output_dir / f'diffusion_cube_c{c}.mp4'
    writer = imageio.get_writer(str(video_path), fps=30, codec='libx264')
    for frame in combined_frames:
        writer.append_data(frame)
    writer.close()
    logging.info(
        f"  Video saved: {video_path} (WM: {len(frames_wm)} steps, De: {len(frames_de)} steps)"
    )


