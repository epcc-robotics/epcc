"""Collect single-cube expert demonstrations with constrained init + FIXED goal,
for training a history-conditioned diffusion planner.

Difference from collect_expert_cube.py:
  - Initial cube position: random within a user-defined left-half rectangle
    (default: x in [0.30, 0.55], y in [-0.30, 0.00]).
  - Target (goal) position: FIXED single point (default: (0.425, 0.15, 0.02)).
  - Manual episode loop with reset() override, mirroring collect_expert_scene.py.
  - Uses CubeMarkovOracle directly (single subtask, no drawer/window/button).

Resulting h5 is drop-in compatible with scripts/cache_latents.py and
latent_diffusion/latent_diffusion/dataset.py (same keys: latent/source observation/
ep_len/ep_offset/ep_success/valid_len are regenerated by downstream tooling).

Usage:
    python collect_diffusion_cube.py                        # collect default 2000 eps
    python collect_diffusion_cube.py num_traj=50            # small smoke run
    python collect_diffusion_cube.py debug_cube=true        # per-step oracle log
"""

