# Validate mode — c-sweep TTC / success-rate check
# ---------------------------------------------------------------------------
def validate_slowdown(cfg):
    """Sweep c values, collect small datasets, report TTC + success rate.
    Uses the same FixedGoalCubePolicy so results reflect the diffusion task
    (not the stock OGBench cube randomization)."""
    cache_dir = cfg.cache_dir or swm.data.utils.get_cache_dir()
    c_values = list(cfg.get('c_sweep', [1.0, 0.8, 0.6, 0.4, 0.3, 0.2, 0.1]))
    if 1.0 not in c_values:
        c_values = [1.0] + c_values
    n_val = int(cfg.get('n_val_episodes', 50))

    output_dir = Path(cache_dir) / 'validation'
    output_dir.mkdir(parents=True, exist_ok=True)

    save_video = bool(cfg.get('save_video', False))

    # One env reused across c values + collection AND video (avoids EGL crash).
    env = gym.make(
        'swm/OGBCube-v0',
        mode='data_collection',
        render_mode='rgb_array',
        width=cfg.world.image_shape[0],
        height=cfg.world.image_shape[1],
        max_episode_steps=cfg.world.max_episode_steps,
        terminate_at_goal=False,
        visualize_info=False,
    )

    results = []
    for c in c_values:
        # c=1.0 is the raw-speed baseline (matches upstream convention)
        noise = 0.1 if c == 1.0 else cfg.get('action_noise', 0.0)
        name = f"validation/cube_diffusion_c{c}"
        logging.info(f"Collecting {n_val} episodes at c={c} (noise={noise})...")
        ep_lens, successes = collect(
            cfg, c, name, n_val, cache_dir, env=env, action_noise=noise
        )

        max_steps = cfg.world.max_episode_steps
        successful_ttc = ep_lens[successes] if successes.any() else np.array([])
        r = {
            'c': float(c),
            'success_rate': float(successes.mean()),
            'avg_ttc': float(successful_ttc.mean()) if len(successful_ttc) > 0 else float('inf'),
            'std_ttc': float(successful_ttc.std()) if len(successful_ttc) > 0 else 0.0,
            'n_success': int(successes.sum()),
            'n_episodes': int(len(ep_lens)),
        }
        results.append(r)
        logging.info(
            f"  c={c:.2f} | success={r['success_rate']:.1%} | "
            f"TTC={r['avg_ttc']:.1f} ± {r['std_ttc']:.1f}"
        )

        # Record side-by-side comparison video for this c (skip c=1.0 baseline)
        if save_video and c != 1.0:
            logging.info(f"  Recording comparison video for c={c}...")
            record_comparison_video(
                cfg, c, output_dir / 'videos', env, seed=42,
            )

    env.close()

    # CSV dump
    import csv
    csv_path = output_dir / 'diffusion_cube_slowdown_validation.csv'
    with open(csv_path, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(results[0].keys()))
        w.writeheader()
        w.writerows(results)
    logging.info(f"CSV saved: {csv_path}")

    # Plot: TTC vs c + success rate vs c (same layout as collect_expert_cube.py)
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt

        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

        baseline = next(r for r in results if r['c'] == 1.0)
        other_results = [r for r in results if r['c'] != 1.0]

        oc_vals = [r['c'] for r in other_results]
        oc_ttc = [r['avg_ttc'] for r in other_results]
        oc_std = [r['std_ttc'] for r in other_results]

        # Plot 1: TTC vs c
        ax1.errorbar(oc_vals, oc_ttc, yerr=oc_std, marker='o', capsize=5, label='D_e')
        ax1.axhline(
            y=baseline['avg_ttc'], color='r', linestyle='--',
            label=f"D_WM (c=1.0): {baseline['avg_ttc']:.0f} steps, "
                  f"SR={baseline['success_rate']:.0%}",
        )
        if baseline['std_ttc'] > 0:
            ax1.axhspan(
                baseline['avg_ttc'] - baseline['std_ttc'],
                baseline['avg_ttc'] + baseline['std_ttc'],
                alpha=0.1, color='r',
            )
        ax1.set_xlabel('Slowdown Factor (c)')
        ax1.set_ylabel('Task Completion Time (steps)')
        ax1.set_title('Diffusion Cube (fixed goal): TTC vs Slowdown Factor')
        ax1.invert_xaxis()
        ax1.legend()
        ax1.grid(True, alpha=0.3)

        # Plot 2: Success rate vs c (bar)
        all_c = [r['c'] for r in results]
        all_sr = [r['success_rate'] for r in results]
        colors = ['red' if c == 1.0 else 'steelblue' for c in all_c]
        ax2.bar(
            range(len(all_c)), all_sr,
            tick_label=[f'{c:.1f}' for c in all_c],
            color=colors,
        )
        ax2.set_xlabel('Slowdown Factor (c)')
        ax2.set_ylabel('Success Rate')
        ax2.set_title(
            'Diffusion Cube (fixed goal): Success Rate vs Slowdown Factor\n'
            '(red = D_WM baseline)'
        )
        ax2.set_ylim(0, 1.1)
        ax2.axhline(y=1.0, color='g', linestyle='--', alpha=0.5)
        ax2.grid(True, alpha=0.3, axis='y')

        plt.tight_layout()
        png_path = output_dir / 'diffusion_cube_slowdown_validation.png'
        plt.savefig(png_path, dpi=150)
        plt.close()
        logging.info(f"Plot saved: {png_path}")
    except ImportError:
        logging.warning("matplotlib not available — skipping plot")

    # Summary table
    logging.info("\n=== Validation Summary (fixed-goal cube) ===")
    logging.info(f"{'c':>6} | {'Success':>8} | {'TTC':>14}")
    logging.info("-" * 38)
    for r in results:
        logging.info(
            f"  c={r['c']:.2f} | {r['success_rate']:>7.1%} | "
            f"{r['avg_ttc']:>6.1f} ± {r['std_ttc']:<5.1f}"
        )

    # Sanity checks
    baseline = next(r for r in results if r['c'] == 1.0)
    slow_results = [r for r in results if r['c'] < 1.0]
    # TTC must INCREASE as c DECREASES. Sort by c descending, then check TTC non-decreasing.
    finite = [r for r in results if r['avg_ttc'] != float('inf')]
    sorted_by_c = sorted(finite, key=lambda r: -r['c'])
    ttc_monotonic = all(
        sorted_by_c[i]['avg_ttc'] <= sorted_by_c[i + 1]['avg_ttc']
        for i in range(len(sorted_by_c) - 1)
    )
    all_success = all(r['success_rate'] > 0.9 for r in results)
    slower_than_baseline = all(
        r['avg_ttc'] > baseline['avg_ttc'] for r in slow_results
        if r['avg_ttc'] != float('inf')
    )
    logging.info(f"\n  Baseline (c=1.0): TTC={baseline['avg_ttc']:.1f}, SR={baseline['success_rate']:.1%}")
    logging.info(f"[CHECK 1] TTC monotone in c: {'PASS' if ttc_monotonic else 'FAIL'}")
    logging.info(f"[CHECK 2] SR > 90% all c: {'PASS' if all_success else 'FAIL'}")
    logging.info(f"[CHECK 3] c<1.0 slower than baseline: {'PASS' if slower_than_baseline else 'FAIL'}")


